"""
Writer for the complete Abaqus/Explicit input deck of the CAI model.

The deck is a flat model (no ``*Part``/``*Assembly``): global node and element
labels, with all sets and surfaces defined at model level. It contains
everything CompDam needs, including the keywords Abaqus/CAE cannot write
(named ``*Depvar``, ``*Characteristic Length, definition=USER``,
``*Initial Conditions, type=SOLUTION`` and the ``COMPDAM_PARAM`` parameter
tables). It runs with ``abaqus job=<name> double=both`` and the pre-compiled
CompDam library given in ``abaqus_v6.env``.

Pure Python: no Abaqus, no numpy.
"""

from __future__ import division, print_function

import datetime
import io
import math

from cai import __version__
from cai import compdam
from cai.model import CATEGORY_SETS

AMPLITUDE = "AMP_SMOOTH_RAMP"
SECTION_CONTROLS = "EC_COMPDAM"
COHESIVE_PROPERTY = "IP_COHESIVE"
FRICTION_PROPERTY = "IP_FRICTION"


def _labels(labels, per_line=16):
    """Format integer labels, ``per_line`` per data line."""
    out = []
    for i in range(0, len(labels), per_line):
        out.append(", ".join("%d" % v for v in labels[i:i + per_line]))
    return out


class DeckWriter(object):
    """Write the CAI input deck.

    Parameters
    ----------
    job : cai.builder.CAIJob
        Fully built job (laminate, damage map, cohesive sizing and mesh).
    """

    def __init__(self, job):
        self.job = job
        self.cfg = job.cfg
        self.mesh = job.mesh
        self.lines = []

    # ------------------------------------------------------------ helpers
    def add(self, *lines):
        self.lines.extend(lines)

    def comment(self, title):
        self.add("**", "** " + title, "**")

    def elset(self, name, labels):
        self.add("*Elset, elset=%s" % name)
        self.add(*_labels(labels))

    def nset(self, name, labels):
        self.add("*Nset, nset=%s" % name)
        self.add(*_labels(sorted(set(labels))))

    def surface(self, name, faces):
        """Element-based surface from ``{face_id: labels}`` (empty faces skipped)."""
        data = []
        for face in sorted(faces):
            labels = faces[face]
            if not labels:
                continue
            es = "_%s_%s" % (name, face)
            self.elset(es, labels)
            data.append("%s, %s" % (es, face))
        if not data:
            return False
        self.add("*Surface, type=ELEMENT, name=%s" % name)
        self.add(*data)
        return True

    # ------------------------------------------------------------ sections
    def heading(self):
        j = self.job
        self.add("*Heading",
                 " %s | %s | impact %.1f J | %s" % (
                     j.name, self.cfg["MODEL"].get("description", ""), j.energy,
                     j.material_name),
                 "** Generated by compdam-cai %s on %s" % (
                     __version__, datetime.datetime.now().strftime("%Y-%m-%d %H:%M")),
                 "** Units: N, mm, s, tonne. X = loading direction, Z = thickness.",
                 "** Run: abaqus job=%s double=both (CompDam library via usub_lib_dir)" % j.name,
                 "*Preprint, echo=NO, model=NO, history=NO, contact=NO")

    def nodes_and_elements(self, fh):
        """Stream nodes and elements straight to the file (they dominate the size)."""
        m = self.mesh
        fh.write(u"**\n** NODES\n**\n*Node\n")
        for bm in m.blocks:
            fh.write(u"".join(u"%d, %.8g, %.8g, %.8g\n" % n for n in bm.iter_nodes()))
        t = self.job.laminate.thickness
        fh.write(u"*Node, nset=RP_LOAD\n%d, %.8g, %.8g, %.8g\n" % (
            m.rp_label, m.L + 5.0, 0.5 * m.W, 0.5 * t))
        fh.write(u"**\n** ELEMENTS (C3D8R, one block per ply group)\n**\n")
        for bm in m.blocks:
            fh.write(u"*Element, type=C3D8R, elset=%s\n" % bm.block.name)
            fh.write(u"".join(u"%d, %d, %d, %d, %d, %d, %d, %d, %d\n" % e
                              for e in bm.iter_elements()))

    def sets(self):
        m = self.mesh
        self.comment("ELEMENT SETS")
        for ply, first, last in m.ply_ranges():
            self.add("*Elset, elset=%s, generate" % ply.name, "%d, %d, 1" % (first, last))
        self.add("*Elset, elset=ALL_PLIES, generate", "1, %d, 1" % m.n_elements)
        cats = m.damage_categories()
        self.job.category_counts = dict((c, len(v)) for c, v in cats.items())
        self.job.ic_sets = []
        for cat, name in CATEGORY_SETS:
            if cats[cat]:
                self.elset(name, cats[cat])
                self.job.ic_sets.append((name, cat))

        self.comment("NODE SETS (ASTM D7137 fixture)")
        for name, labels in sorted(m.node_sets().items()):
            self.nset(name, labels)

        self.comment("SURFACES")
        self.surface("END_XL", m.end_faces(m.L))
        self.job.contact_pairs = []
        if self.cfg["INTERFACE"]["type"] == "tie":
            for itf in self.job.laminate.interfaces:
                lo = m.blocks[itf.lower.index - 1]
                up = m.blocks[itf.upper.index - 1]
                f, labels = m.block_faces(lo, top=True)
                self.surface("%s_LOWER" % itf.name, {f: labels})
                f, labels = m.block_faces(up, top=False)
                self.surface("%s_UPPER" % itf.name, {f: labels})
            return
        for entry in m.interface_surfaces():
            itf = entry["interface"]
            names = {}
            for side in ("lower", "upper"):
                face, labels = entry[side]["bonded"]
                sname = "%s_%s_BONDED" % (itf.name, side.upper())
                names[side] = sname if self.surface(sname, {face: labels}) else None
            if names["lower"] and names["upper"]:
                self.job.contact_pairs.append((names["lower"], names["upper"]))

    def sections(self):
        m = self.cfg["MESH"]
        self.comment("PLY ORIENTATIONS AND SECTIONS (1 = fibre, 3 = stacking direction)")
        opts = []
        if m.get("distortion_control", True):
            opts.append("distortion control=YES")
        hg = m.get("hourglass_control", "ENHANCED").upper()
        if hg != "DEFAULT":
            opts.append("hourglass=%s" % hg.replace("_", " "))
        ks = m.get("kinematic_split", "AVERAGE_STRAIN").upper()
        opts.append("kinematic split=%s" % ks.replace("_", " "))
        self.add("*Section Controls, name=%s, %s" % (SECTION_CONTROLS, ", ".join(opts)))
        for ply in self.job.laminate.plies:
            t = math.radians(ply.angle)
            c, s = math.cos(t), math.sin(t)
            self.add("*Orientation, name=ORI_%s, system=RECTANGULAR" % ply.name,
                     "%.10g, %.10g, 0., %.10g, %.10g, 0." % (c, s, -s, c),
                     "3, 0.",
                     "*Solid Section, elset=%s, orientation=ORI_%s, material=%s, controls=%s"
                     % (ply.name, ply.name, self.job.material_name, SECTION_CONTROLS),
                     ",")

    def constraints(self):
        self.comment("LOAD INTRODUCTION AND INTERFACE CONSTRAINTS")
        self.add("*Coupling, constraint name=CPL_LOADED_END, ref node=RP_LOAD, surface=END_XL",
                 "*Kinematic",
                 "1, 1")
        if self.cfg["INTERFACE"]["type"] == "tie":
            for itf in self.job.laminate.interfaces:
                self.add("*Tie, name=TIE_%s, adjust=YES" % itf.name,
                         "%s_LOWER, %s_UPPER" % (itf.name, itf.name))

    def amplitude(self):
        T = float(self.cfg["STEP"]["time_period"])
        self.add("*Amplitude, name=%s, definition=SMOOTH STEP" % AMPLITUDE,
                 "0., 0., %.8g, 1." % T)

    def material(self):
        j = self.job
        c = self.cfg["COMPDAM"]
        self.comment("COMPDAM_DGD MATERIAL (VUMAT)")
        self.add("*Material, name=%s" % j.material_name,
                 "*Density",
                 " %.8g," % j.material["density"])
        self.add("*Depvar, delete=%d" % compdam.SDV_STATUS if c.get("element_deletion")
                 else "*Depvar",
                 " %d," % j.nstatev)
        self.add(*compdam.format_depvar_names(j.nstatev))
        self.add("*Characteristic Length, definition=USER, components=%d"
                 % int(c.get("characteristic_length_components", 3)))
        self.add("*User Material, constants=40")
        self.add(*compdam.format_user_material(j.material, c["feature_flags"]))

    def interaction_properties(self):
        if self.cfg["INTERFACE"]["type"] != "cohesive":
            return
        sz = self.job.sizing
        itf = self.job.material["interface"]
        self.comment("INTERFACE PROPERTIES (Turon et al. 2007 sizing, see summary.txt)")
        self.add("*Surface Interaction, name=%s" % COHESIVE_PROPERTY,
                 "*Friction", " %.6g," % itf["friction"],
                 "*Cohesive Behavior, eligibility=ORIGINAL CONTACTS",
                 " %.6g, %.6g, %.6g" % (sz.penalty, sz.penalty, sz.penalty),
                 "*Damage Initiation, criterion=QUADS",
                 " %.6g, %.6g, %.6g" % (sz.strength_normal, sz.strength_shear,
                                        sz.strength_shear),
                 "*Damage Evolution, type=ENERGY, mixed mode behavior=BK, power=%.6g"
                 % itf["eta_BK"],
                 " %.6g, %.6g, %.6g" % (itf["GIc"], itf["GIIc"], itf["GIIc"]),
                 "*Surface Interaction, name=%s" % FRICTION_PROPERTY,
                 "*Friction", " %.6g," % itf["friction"])

    def initial_conditions(self):
        j = self.job
        d = self.cfg["DAMAGE"]
        phi0 = self.cfg["COMPDAM"].get("phi0", 0.0)
        mc, fd = d["matrix_cracking"], d["fiber_damage"]
        states = {
            "pristine": compdam.initial_state(j.nstatev, phi0=phi0),
            "matrix": compdam.initial_state(j.nstatev, d2=mc["d2"], alpha=mc["alpha"],
                                            phi0=phi0),
            "fiber": compdam.initial_state(j.nstatev, d2=mc["d2"], alpha=mc["alpha"],
                                           d1T=fd["d1T"], d1C=fd["d1C"], phi0=phi0),
        }
        self.comment("COMPDAM INITIAL STATE (pristine + seeded impact damage)")
        self.add(*compdam.format_initial_conditions(
            [(name, states[cat]) for name, cat in j.ic_sets]).rstrip("\n").splitlines())
        c = self.cfg["COMPDAM"]
        tables = compdam.format_parameter_tables(c.get("parameters_float", {}),
                                                 c.get("parameters_int", {}))
        if tables:
            self.add(*tables.rstrip("\n").splitlines())

    def boundary(self):
        self.comment("BOUNDARY CONDITIONS (ASTM D7137 fixture)")
        self.add("*Boundary",
                 "END_X0, 1, 1",
                 "END_SUPPORTS, 3, 3",
                 "KNIFE_EDGES, 3, 3",
                 "ANCHOR_Y, 2, 2",
                 "RP_LOAD, 1, 6")

    def step(self):
        s = self.cfg["STEP"]
        T = float(s["time_period"])
        d = float(self.cfg["BOUNDARY"]["applied_displacement"])
        self.add("** ----------------------------------------------------------------",
                 "**", "** STEP: %s" % s["name"], "**",
                 "*Step, name=%s, nlgeom=YES" % s["name"],
                 "*Dynamic, Explicit",
                 ", %.8g" % T,
                 "*Bulk Viscosity",
                 "%.6g, %.6g" % (s["linear_bulk_viscosity"], s["quadratic_bulk_viscosity"]))
        if s.get("mass_scaling_target_dt"):
            self.add("*Fixed Mass Scaling, dt=%.6g, type=BELOW MIN" % s["mass_scaling_target_dt"])
        if self.cfg["INTERFACE"]["type"] == "cohesive":
            self.add("**", "** General contact: friction everywhere, cohesive on bonded regions",
                     "*Contact, op=NEW",
                     "*Contact Inclusions, ALL EXTERIOR",
                     "*Contact Property Assignment",
                     " , , %s" % FRICTION_PROPERTY)
            for lo, up in self.job.contact_pairs:
                self.add("%s, %s, %s" % (lo, up, COHESIVE_PROPERTY))
        self.add("**", "*Boundary, amplitude=%s" % AMPLITUDE, "RP_LOAD, 1, 1, %.8g" % (-d))
        elem_vars = ["S", "LE", "SDV"]
        if self.cfg["COMPDAM"].get("element_deletion"):
            elem_vars.append("STATUS")
        self.add("**", "** OUTPUT REQUESTS", "**",
                 "*Output, field, number interval=%d" % int(s["field_output_intervals"]),
                 "*Node Output", "U, RF",
                 "*Element Output, directions=YES", ", ".join(elem_vars))
        if self.cfg["INTERFACE"]["type"] == "cohesive":
            self.add("*Contact Output", "CSTRESS, CSDMG")
        self.add("*Output, history, time interval=%.6g"
                 % (T / int(s["history_output_intervals"])),
                 "*Energy Output",
                 "ALLAE, ALLDMD, ALLFD, ALLIE, ALLKE, ALLPD, ALLSE, ALLVD, ALLWK, ETOTAL",
                 "*Node Output, nset=RP_LOAD",
                 "RF1, U1",
                 "*End Step")

    # ------------------------------------------------------------------ write
    def write(self, path):
        """Write the complete deck to ``path``.

        Parameters
        ----------
        path : str
            Output ``.inp`` path.
        """
        self.lines = []
        self.heading()
        head = self.lines
        self.lines = []
        self.sets()
        self.sections()
        self.constraints()
        self.amplitude()
        self.material()
        self.interaction_properties()
        self.initial_conditions()
        self.boundary()
        self.step()
        with io.open(path, "w", encoding="ascii") as fh:
            fh.write(u"\n".join(head) + u"\n")
            self.nodes_and_elements(fh)
            fh.write(u"\n".join(self.lines) + u"\n")
