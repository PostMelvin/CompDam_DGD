"""
Support files that make each job folder self-contained on a cluster.

For every job the generator writes, next to ``<job>.inp``:

* ``abaqus_v6.env``: points ``usub_lib_dir`` at the pre-compiled CompDam
  library (or holds the Intel Fortran flags when compiling from source),
* ``submit.slurm`` / ``submit.pbs``: batch script for the scheduler,
* ``run.sh``: the same commands without scheduler directives,
* ``postprocess.py``: standalone ``abaqus python`` script that extracts the
  load-displacement curve and the CAI strength and compares it with NCAMP.

Pure Python.
"""

from __future__ import division, print_function

#: Linux Intel Fortran flags required by CompDam (from CompDam tests/abaqus_v6.env).
COMPDAM_LINUX_COMPILE = (
    "compile_fortran = ['ifort', '-free', '-DABQ_LNX86_64',\n"
    "                   '-qmkl=sequential',  # '-mkl=sequential' for Intel compilers before 2021\n"
    "                   '-axCORE-AVX2', '-xSSE3',\n"
    "                   '-V', '-c', '-fPIC', '-auto', '-mP2OPT_hpo_vec_divbyzero=F',\n"
    "                   '-extend-source', '-fpp', '-WB', '-I%I']\n"
)


def env_file(cfg, job_name):
    """Contents of the job's ``abaqus_v6.env``.

    Parameters
    ----------
    cfg : dict
        Loaded configuration.
    job_name : str
        Job name (for the header comment).

    Returns
    -------
    str
    """
    c = cfg["COMPDAM"]
    lines = [
        "# abaqus_v6.env for job %s (generated by compdam-cai)" % job_name,
        "# Abaqus merges this file with the site and home environment files.",
        "import os",
        "",
        "# Avoids hangs in the packager on some systems (CompDam tests/abaqus_v6.env).",
        "os.environ['MPI_FLUSH_FCACHE'] = '100'",
        "",
    ]
    if c.get("library_dir"):
        lines += [
            "# Pre-compiled CompDam_DGD (abaqus make library=CompDam_DGD); no user= needed.",
            "usub_lib_dir = %r" % c["library_dir"],
        ]
    else:
        lines += [
            "# Compile CompDam_DGD from source at run time (user= on the command line).",
            COMPDAM_LINUX_COMPILE.rstrip("\n"),
        ]
    return "\n".join(lines) + "\n"


def abaqus_command(cfg, job_name):
    """Abaqus/Explicit command line for the job.

    Parameters
    ----------
    cfg : dict
        Loaded configuration.
    job_name : str
        Job name.

    Returns
    -------
    str
    """
    cl = cfg["CLUSTER"]
    n = int(cl.get("cpus", 1))
    cmd = ("%s job=%s input=%s.inp double=both cpus=%d parallel=domain domains=%d "
           "mp_mode=%s interactive" % (cl.get("abaqus_command", "abaqus"), job_name, job_name,
                                       n, n, cl.get("mp_mode", "mpi")))
    us = cfg["COMPDAM"].get("user_subroutine")
    if us and not cfg["COMPDAM"].get("library_dir"):
        cmd += " user=%s" % us
    return cmd


def _body(cfg, job_name):
    cl = cfg["CLUSTER"]
    lines = list(cl.get("setup_commands") or [])
    lines.append(abaqus_command(cfg, job_name))
    if cl.get("postprocess", True):
        lines += [
            "if [ -f %s.odb ]; then" % job_name,
            "    %s python postprocess.py %s.odb" % (cl.get("abaqus_command", "abaqus"), job_name),
            "fi",
        ]
    return lines


def run_script(cfg, job_name):
    """Plain shell script running the job in its folder."""
    return "\n".join(["#!/bin/bash", "# Run job %s (generated by compdam-cai)" % job_name,
                      "set -e", 'cd "$(dirname "$0")"'] + _body(cfg, job_name)) + "\n"


def scheduler_script(cfg, job_name):
    """Batch script for SLURM or PBS.

    Parameters
    ----------
    cfg : dict
        Loaded configuration.
    job_name : str
        Job name.

    Returns
    -------
    tuple or None
        ``(file_name, contents)``, or None when ``scheduler == "none"``.
    """
    cl = cfg["CLUSTER"]
    kind = (cl.get("scheduler") or "none").lower()
    n = int(cl.get("cpus", 1))
    if kind == "slurm":
        head = ["#!/bin/bash",
                "#SBATCH --job-name=%s" % job_name[:32],
                "#SBATCH --nodes=%d" % int(cl.get("nodes", 1)),
                "#SBATCH --ntasks=%d" % n,
                "#SBATCH --time=%s" % cl["walltime"],
                "#SBATCH --output=%s.%%j.out" % job_name]
        if cl.get("memory"):
            head.append("#SBATCH --mem=%s" % cl["memory"])
        if cl.get("partition"):
            head.append("#SBATCH --partition=%s" % cl["partition"])
        if cl.get("account"):
            head.append("#SBATCH --account=%s" % cl["account"])
        head += ["#SBATCH %s" % d for d in cl.get("extra_directives") or []]
        head += ["set -e", 'cd "$SLURM_SUBMIT_DIR"']
        return "submit.slurm", "\n".join(head + _body(cfg, job_name)) + "\n"
    if kind == "pbs":
        res = "select=%d:ncpus=%d" % (int(cl.get("nodes", 1)), n)
        if cl.get("memory"):
            res += ":mem=%s" % cl["memory"].lower().replace("g", "gb").replace("gbb", "gb")
        head = ["#!/bin/bash",
                "#PBS -N %s" % job_name[:15],
                "#PBS -l %s" % res,
                "#PBS -l walltime=%s" % cl["walltime"],
                "#PBS -j oe"]
        if cl.get("partition"):
            head.append("#PBS -q %s" % cl["partition"])
        if cl.get("account"):
            head.append("#PBS -A %s" % cl["account"])
        head += ["#PBS %s" % d for d in cl.get("extra_directives") or []]
        head += ["set -e", 'cd "$PBS_O_WORKDIR"']
        return "submit.pbs", "\n".join(head + _body(cfg, job_name)) + "\n"
    return None


POSTPROCESS_TEMPLATE = '''"""
Post-process CAI job %(job)s (standalone; generated by compdam-cai).

Usage:  abaqus python postprocess.py %(job)s.odb

Writes %(job)s_load_displacement.csv and prints the peak load, the CAI
strength (ASTM D7137: P_max / (w h)), the NCAMP comparison and the
quasi-static check (max ALLKE / ALLIE in the second half of the step).
"""
from __future__ import division, print_function
import sys

WIDTH = %(width)r            # mm
THICKNESS = %(thickness)r    # mm
ENERGY = %(energy)r          # J
NCAMP_CAI = %(ncamp_cai)r    # MPa (None if not configured)
NCAMP_EJ_PER_MM = %(ncamp_e)r
NCAMP_VERIFIED = %(verified)r


def main(odb_path):
    from odbAccess import openOdb
    odb = openOdb(odb_path, readOnly=True)
    try:
        step = odb.steps[list(odb.steps.keys())[-1]]
        rp = en = None
        for region in step.historyRegions.values():
            keys = region.historyOutputs.keys()
            if "U1" in keys and "RF1" in keys:
                rp = region
            if "ALLKE" in keys and "ALLIE" in keys:
                en = region
        if rp is None:
            raise RuntimeError("no RP_LOAD history (U1, RF1) in " + odb_path)
        u = rp.historyOutputs["U1"].data
        f = rp.historyOutputs["RF1"].data
        ratio = None
        if en is not None:
            ke = en.historyOutputs["ALLKE"].data
            ie = en.historyOutputs["ALLIE"].data
            half = len(ie) // 2
            r = [k[1] / i[1] for k, i in zip(ke[half:], ie[half:]) if abs(i[1]) > 1e-12]
            ratio = max(r) if r else None
    finally:
        odb.close()

    csv_path = odb_path[:-4] + "_load_displacement.csv"
    with open(csv_path, "w") as fh:
        fh.write("time_s,end_shortening_mm,load_N\\n")
        for (t, ui), (_, fi) in zip(u, f):
            fh.write("%%.6e,%%.6e,%%.6e\\n" %% (t, -ui, -fi))

    peak = max(-fi for _, fi in f)
    strength = peak / (WIDTH * THICKNESS)
    print("Peak compressive load: %%.0f N" %% peak)
    print("CAI strength: %%.1f MPa (impact %%.1f J, %%.2f J/mm)"
          %% (strength, ENERGY, ENERGY / THICKNESS))
    if NCAMP_CAI:
        print("NCAMP CAI strength: %%.1f MPa at %%.2f J/mm -> delta %%.1f %%%%%%s"
              %% (NCAMP_CAI, NCAMP_EJ_PER_MM, 100.0 * (strength - NCAMP_CAI) / NCAMP_CAI,
                 "" if NCAMP_VERIFIED else "  [baseline NOT verified]"))
    if ratio is not None:
        print("Max ALLKE/ALLIE (2nd half): %%.3f %%s" %% (
            ratio, "(OK)" if ratio < 0.05 else "(> 5 %%: load more slowly)"))
    print("Load-displacement curve: " + csv_path)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--"]
    main(args[0] if args else "%(job)s.odb")
'''


def postprocess_script(cfg, job_name, thickness, energy):
    """Standalone ``abaqus python`` post-processing script for one job.

    Parameters
    ----------
    cfg : dict
        Loaded configuration.
    job_name : str
        Job name.
    thickness : float
        Laminate thickness [mm].
    energy : float
        Impact energy [J].

    Returns
    -------
    str
    """
    base = cfg["NCAMP_BASELINE"].get(cfg["LAYUP"]["material"]) or {}
    cai = base.get("cai") or {}
    return POSTPROCESS_TEMPLATE % {
        "job": job_name,
        "width": float(cfg["GEOMETRY"]["width"]),
        "thickness": round(float(thickness), 6),
        "energy": float(energy),
        "ncamp_cai": cai.get("cai_strength"),
        "ncamp_e": cai.get("impact_energy_per_thickness"),
        "verified": bool(base.get("verified", False)),
    }
